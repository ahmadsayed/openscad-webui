// Prompt: make a gear with 15 teeth and 5mm thickness
// Modules used: gear
// Default facets: 16

include <module.scad>;

// Gear parameters
number_of_teeth = 15;
circular_pitch = 200;
pressure_angle = 20;
gear_thickness = 5;
facets = 16;

// Create gear
linear_extrude(height = gear_thickness, center = true, $fn = facets) {
    gear(
        number_of_teeth = number_of_teeth,
        circular_pitch = circular_pitch,
        pressure_angle = pressure_angle
    );
}
EOF
echo "✅ Generated: gear-15-teeth.scad"

# Test 3: Code Modification
