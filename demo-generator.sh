# Test 1: Rounded Cube
echo -e "\n${GREEN}Test 1: Creating rounded cube with 25mm sides${NC}"
cat > "${OUTPUT_DIR}/rounded-cube-25.scad" << 'EOF'
// Generated by OpenSCAD Generator
// Prompt: create a rounded cube with 25mm sides
// Modules used: rounded_cube
// Default facets: 16

include <module.scad>;

// Parameters
size = [25, 25, 25];  // Cube dimensions in mm
radius = 3;           // Corner radius
facets = 16;          // Number of facets for rounded edges

// Create rounded cube
rounded_cube(size, radius, facets);
EOF
echo "✅ Generated: rounded-cube-25.scad"

# Test 2: Gear
