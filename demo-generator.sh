// Create rounded cube
rounded_cube(size, radius, facets);

// Changes made from original code:
// 1. Replaced simple cube() with parameterized rounded_cube() module
// 2. Added adjustable corner radius parameter
// 3. Added facets parameter for smoothness control
EOF
echo "✅ Generated: cube-rounded-15.scad"

